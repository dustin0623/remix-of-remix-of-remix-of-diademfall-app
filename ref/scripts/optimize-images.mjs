import sharp from "sharp";
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { wireWebp } from "./wire-webp.mjs";
import path from "node:path";

// PNGs remain the source of truth. Run npm run assets:optimize after replacing art.
const root = process.cwd();
const groups = [
  ["Cards", "public/assets/heroes", false],
  ["Avatars", "public/assets/avatars", false],
  ["Backgrounds", "public/assets/backgrounds", false],
  ["HUD", "public/game/hud", false],
  ["Skills", "public/game/skills", false],
  ["Stats", "public/game/stats", false],
  ["Emblems", "public/game/emblems", false],
];
sharp.concurrency(1);
const mapping = {};
const rows = [];
async function files(folder) {
  const result = [];
  for (const entry of await readdir(folder, { withFileTypes: true })) {
    const name = path.join(folder, entry.name);
    if (entry.isDirectory()) result.push(...await files(name));
    else if (entry.name.endsWith(".png")) result.push(name);
  }
  return result.sort();
}
function compare(a, b, lossless) {
  if (a.length !== b.length) throw Error("Decoded image dimensions changed");
  let squared = 0, count = 0;
  for (let i = 0; i < a.length; i += 4) {
    if (a[i + 3] !== b[i + 3]) throw Error("Alpha channel changed");
    if (!a[i + 3]) continue; // RGB under fully transparent pixels is invisible.
    for (let c = 0; c < 3; c++) {
      const diff = a[i+c] - b[i+c];
      if (lossless && diff) throw Error("Visible pixel changed in lossless output");
      squared += diff * diff; count++;
    }
  }
  return squared ? 10 * Math.log10(255 * 255 / (squared / count)) : Infinity;
}
for (const [group, relative, lossy] of groups) {
  const sources = await files(path.join(root, relative));
  for (const source of sources) {
    const original = await readFile(source);
    const metadata = await sharp(original).metadata();
    const decoded = await sharp(original).ensureAlpha().raw().toBuffer();
    let output, psnr;
    for (const quality of lossy ? [88, 92, 96] : [100]) {
      const existing = process.argv.includes("--reuse") && !lossy ? await readFile(source.replace(/\.png$/, ".webp")).catch(() => null) : null;
      output = existing ?? await sharp(original).webp({ lossless: !lossy, quality, alphaQuality: 100, effort: 5 }).toBuffer();
      const converted = await sharp(output).metadata();
      if (metadata.width !== converted.width || metadata.height !== converted.height) throw Error("Image resized");
      psnr = compare(decoded, await sharp(output).ensureAlpha().raw().toBuffer(), !lossy);
      if (!lossy || psnr >= 35) break;
    }
    const accepted = output.length < original.length && (!lossy || psnr >= 35);
    const relativeUrl = "/" + path.relative(path.join(root, "public"), source).replaceAll("\\", "/");
    const destination = source.replace(/\.png$/, ".webp");
    if (accepted) {
      await writeFile(destination, output);
      mapping[relativeUrl] = relativeUrl.replace(/\.png$/, ".webp");
    }
    rows.push({ group, url: relativeUrl, before: original.length, after: accepted ? output.length : original.length, accepted, psnr, lossless: !lossy });
  }
  console.log(group + ": verified " + sources.length + " images");
}
await mkdir(path.join(root, "src/lib/assets"), { recursive: true });
await writeFile(path.join(root, "src/lib/assets/optimized-images.ts"),
  "/** Generated by npm run assets:optimize. Only smaller, verified derivatives are selected. */\n" +
  "const WEBP: Record<string, string> = " + JSON.stringify(mapping, null, 2) + ";\n\n" +
  "export function optimizedImage(url: string): string {\n" +
  "  const index = url.search(/[?#]/);\n" +
  "  const base = index < 0 ? url : url.slice(0, index);\n" +
  "  return (WEBP[base] ?? base) + (index < 0 ? \"\" : url.slice(index));\n}\n");
// CSS and preload literals can reference the verified derivatives directly.
for (const folder of ["src/styles", "src/routes"]) {
  for (const name of await readdir(path.join(root, folder))) {
    if (!/\.(css|tsx)$/.test(name)) continue;
    const target = path.join(root, folder, name);
    let content = await readFile(target, "utf8");
    const before = content;
    for (const [png, webp] of Object.entries(mapping)) content = content.replaceAll(png, webp);
    if (content !== before) await writeFile(target, content);
  }
}
const summaries = groups.map(([group]) => {
  const list = rows.filter(row => row.group === group);
  const before = list.reduce((n, row) => n + row.before, 0);
  const after = list.reduce((n, row) => n + row.after, 0);
  return { group, count: list.length, converted: list.filter(row => row.accepted).length, before, after, saved: ((1-after/before)*100).toFixed(1) + "%" };
});
await mkdir(path.join(root, "docs"), { recursive: true });
await writeFile(path.join(root, "docs/webp-report.md"),
  "# WebP asset verification\n\nRun: npm run assets:optimize. Originals retained. No runtime conversion or resizing. All current groups use lossless WebP. Every visible RGBA pixel, alpha channel and image dimension is verified against the PNG source. Only smaller derivatives enter the generated URL map. SVG and Phaser source loaders remain unchanged.\n\n" +
  "| Group | Images | Converted | PNG bytes | Served bytes | Saved |\n|---|---:|---:|---:|---:|---:|\n" +
  summaries.map(s => `| ${s.group} | ${s.count} | ${s.converted} | ${s.before} | ${s.after} | ${s.saved} |`).join("\n") +
  "\n\n| Source | PNG bytes | Served bytes | Validation |\n|---|---:|---:|---|\n" +
  rows.map(r => `| ${r.url} | ${r.before} | ${r.after} | ${!r.accepted ? "Kept PNG" : r.lossless ? "Visible RGBA exact" : "PSNR " + r.psnr.toFixed(2) + " dB"} |`).join("\n") + "\n");
console.log(JSON.stringify(summaries, null, 2));
await wireWebp();
